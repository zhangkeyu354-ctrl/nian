import { chromium, type Page } from "playwright";
import { strict as assert } from "node:assert";
const base = "http://127.0.0.1:3184", out = "/tmp/k3";
const b = await chromium.launch({ executablePath: process.env.PW_CHROME });
const pages = await Promise.all(Array.from({length:8}, async()=> (await b.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})).newPage()));
const errors:string[]=[]; pages.forEach(p=>p.on("pageerror",e=>errors.push(e.message)));
const st = (p:Page)=>p.evaluate(()=>JSON.parse((window as any).render_game_to_text()));
const wait = (p:Page, ph:string)=>p.waitForFunction((ph)=>{try{return JSON.parse((window as any).render_game_to_text()).view?.phase===ph}catch{return false}},ph,{timeout:20000});
const shot=(p:Page,n:string,d=600)=>p.waitForTimeout(d).then(()=>p.screenshot({path:`${out}/${n}.png`}));
await pages[0].goto(base+"/?game=dm");
await pages[0].getByTestId("dm-create").click();
await pages[0].getByLabel("你的昵称").fill("P1");
await pages[0].getByRole("button",{name:"入座",exact:true}).click();
await pages[0].getByTestId("dm-ready").waitFor();
await pages[0].getByLabel("本局人数").selectOption("8");
await pages[0].getByTestId("dm-seat-8").waitFor();
const code=(await st(pages[0])).code;
for(let i=1;i<8;i++){await pages[i].goto(base+"/?game=dm&room="+code);await pages[i].getByLabel("你的昵称").fill("P"+(i+1));await pages[i].getByRole("button",{name:"入座",exact:true}).click();await pages[i].getByTestId("dm-ready").waitFor();}
await pages[0].getByLabel("杀手 2",{exact:true}).selectOption("serial-killer");
await pages[0].waitForTimeout(400);
await pages[0].getByLabel("无罪 1",{exact:true}).selectOption("wonder-dog");
await pages[0].waitForTimeout(600);
for(const p of pages) await p.getByTestId("dm-ready").click();
await pages[0].getByTestId("dm-start").click();
await pages[0].waitForFunction(()=>JSON.parse((window as any).render_game_to_text()).view);
let views=await Promise.all(pages.map(st));
const idx=(role:string)=>views.map((s,i)=>[s,i] as const).filter(([s])=>s.view.me.roleId===role).map(([,i])=>i);
const dog=idx("wonder-dog")[0], ks=[...idx("killer"),...idx("serial-killer")];
const seat=(i:number)=>views[i].view.players.find((p:any)=>p.id===views[i].view.me.id).seat;
// 名犬
await wait(pages[dog],"NIGHT_PREPARATION");
await pages[dog].locator(".dm-banner").waitFor({timeout:3000}).catch(()=>{});
await shot(pages[dog],"1-dog-banner",300);
const civ=views.map((_,i)=>i).filter(i=>!ks.includes(i)&&i!==dog);
const prot=civ[0];
await pages[dog].getByTestId("dm-seat-"+seat(prot)).click();
assert.match(await pages[dog].getByTestId("dm-prepare").innerText(), new RegExp("保护 "+seat(prot)+"号"));
await shot(pages[dog],"2-dog-pick",1900);
await pages[dog].getByTestId("dm-prepare").click();
// 杀手密语
await Promise.all(ks.map(k=>wait(pages[k],"KILLER_SELECTION")));
const [a,c]=ks;
await pages[a].getByTestId("dm-whisper").waitFor();
await pages[a].getByLabel("密语内容").fill("杀"+seat(civ[1])+"和"+seat(civ[2]));
await pages[a].getByTestId("dm-whisper-send").click();
await pages[c].getByTestId("dm-whisper").getByText("杀"+seat(civ[1])+"和"+seat(civ[2])).waitFor();
await pages[a].getByLabel("密语内容").fill("同意吗");
await pages[a].getByTestId("dm-whisper-send").click();
await pages[a].getByText("你还能说 0 句").waitFor();
assert.equal(await pages[a].getByLabel("密语内容").isDisabled(), true);
assert.equal(await pages[civ[3]].getByTestId("dm-whisper").count(), 0);
// 保护目标不可选
assert.equal(await pages[a].getByTestId("dm-seat-"+seat(prot)).isDisabled(), true);
const order=[civ[2],civ[1]];
for(const t of order) await pages[a].getByTestId("dm-seat-"+seat(t)).click();
await pages[a].getByTestId("dm-kill").click();
await pages[c].locator(".dm-mate").first().waitFor();
await shot(pages[c],"3-killer-whisper-mate",2000);
for(const t of order) await pages[c].getByTestId("dm-seat-"+seat(t)).click();
await pages[c].getByTestId("dm-kill").click();
// 按顺序：order[0] 先选
await wait(pages[order[0]],"VICTIM_EVIDENCE");
let v0=(await st(pages[order[0]])).view, v1=(await st(pages[order[1]])).view;
assert.equal(v0.active,true); assert.equal(v1.active,false);
assert.equal(v0.evidenceStep.total,2);
await shot(pages[order[1]],"4-victim2-waiting",2000);
await pages[order[0]].locator("[data-card]").nth(0).click();
await pages[order[0]].getByTestId("dm-evidence-confirm").click();
await pages[order[1]].waitForFunction(()=>JSON.parse((window as any).render_game_to_text()).view.active);
await shot(pages[order[1]],"5-victim2-turn",600);
await pages[order[1]].locator("[data-card]").nth(0).click();
await pages[order[1]].getByTestId("dm-evidence-confirm").click();
// 假遗言 + 编号
await wait(pages[a],"KILLER_FAKE_EVIDENCE");
await pages[a].locator("[data-card]").nth(2).click();
await pages[a].locator("[data-card]").nth(5).click();
await pages[a].getByLabel("密语内容").fill("选3和6");
await pages[a].getByTestId("dm-whisper-send").click();
await pages[a].getByTestId("dm-evidence-confirm").click();
await pages[c].locator("[data-card] .dm-mate").first().waitFor();
await shot(pages[c],"6-fake-mate",800);
await pages[c].locator("[data-card]").nth(2).click();
await pages[c].locator("[data-card]").nth(5).click();
await pages[c].getByTestId("dm-evidence-confirm").click();
await wait(pages[a],"INVESTIGATION");
const h=(await st(pages[a])).view.history[0];
assert.equal(h.cards.length,4);
assert.deepEqual(errors,[]);
console.log("PASS");
await b.close();
